// Generate client.js from the modules and stylesheet in src/.
// Usage: node scripts/build.mjs          (write client.js)
//        node scripts/build.mjs --check  (fail when client.js is stale)
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const pkg = JSON.parse(readFileSync(`${root}package.json`, 'utf8'))
const css = readFileSync(`${root}src/mobile.css`, 'utf8')
const runtime = readFileSync(`${root}src/runtime.js`, 'utf8')
const settings = readFileSync(`${root}src/settings.js`, 'utf8')
const header = readFileSync(`${root}src/header.js`, 'utf8')

const problems = []
if (!/^export function install\(/m.test(runtime)) problems.push('src/runtime.js must export function install')
if ([runtime, settings, header].some(source => /^import /m.test(source))) problems.push('src/ modules must not import anything; they are inlined into client.js')

const indent = text => text.trimEnd().split('\n').map(line => (line ? `    ${line}` : line)).join('\n')
const source = `// Generated by scripts/build.mjs from src/ — do not edit by hand.
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    const CSS = ${JSON.stringify(css)};
${indent(settings.replace(/^export /gm, ''))}
${indent(header.replace(/^export /gm, ''))}
${indent(runtime.replace(/^export /gm, ''))}
    return {
      inject: ['layout', 'slots', 'locale', 'configForms'],
      apply(ctx) {
        const html = document.documentElement;
        if (html.dataset.platform === 'darwin' || html.hasAttribute('data-windows-titlebar')) return;
        const preference = createHeaderPreference(ctx.configForms.get(${JSON.stringify(pkg.name)}));
        ctx.effect(() => () => preference.dispose(), ${JSON.stringify(`${pkg.name}: preference`)});
        ctx.effect(() => ctx.locale.register(SETTINGS_NAMESPACE, SETTINGS_COPY), ${JSON.stringify(`${pkg.name}: dictionaries`)});
        const Row = createHeaderSettingsRow(require('react'), require('@deepseek-ai/dsh-client-ui-primitives').Switch, preference);
        ctx.slots.inject('settings.general.item', () => ctx.slots.register({
          name: 'settings.general.item', id: 'dsh-mobile-fix-header', order: 25, locale: SETTINGS_NAMESPACE,
        }, Row));
        ctx.effect(() => install({ layout: ctx.layout, css: CSS, preference }), ${JSON.stringify(`${pkg.name}: layout`)});
      },
    };
  },
});
`

const target = `${root}client.js`
const check = process.argv.includes('--check')
if (check) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== source) problems.push('client.js is stale; run npm run build')
} else {
  writeFileSync(target, source)
}
if (problems.length > 0) {
  for (const problem of problems) console.error(problem)
  process.exit(1)
}
console.log(check ? 'client.js is current' : `wrote client.js (${source.length} bytes)`)
